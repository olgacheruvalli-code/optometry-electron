// Runs automatically before `npm run build` (prebuild).
// Stamps a unique build id into the app AND into public/version.json,
// so running apps can tell when a newer version has been deployed.
const fs = require("fs");
const path = require("path");
const id = new Date().toISOString().replace(/[-:.TZ]/g, "").slice(0, 14);
fs.writeFileSync(
  path.join(__dirname, "..", "public", "version.json"),
  JSON.stringify({ buildId: id }) + "\n"
);
fs.writeFileSync(
  path.join(__dirname, "..", "src", "buildInfo.js"),
  `// Auto-generated by scripts/write-version.js — do not edit\nexport const BUILD_ID = "${id}";\n`
);
console.log("Build id:", id);
